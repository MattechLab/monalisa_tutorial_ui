function identity = main_scan_identity(rawInfo)
%MAIN_SCAN_IDENTITY Bounded provenance check; raw file is NOT fully hashed.
% Includes raw path/size/mtime, complete sequence-file hash, grouping and FoV.
identity = struct('rawFile',rawInfo.rawFile,'rawBytes',rawInfo.rawStat.bytes, ...
    'rawModified',rawInfo.rawStat.datenum,'seqFile',rawInfo.seqFile, ...
    'sequenceMD5',file_md5(rawInfo.seqFile),'nCh',rawInfo.nCh, ...
    'N',rawInfo.N,'nSeg',rawInfo.nSeg,'nShot',rawInfo.nShot, ...
    'FoV',rawInfo.FoV,'headerSignature',rawInfo.headerSignature, ...
    'flagSelfNav',rawInfo.sequenceParams.flagselfnav);
end
